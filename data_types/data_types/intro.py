"""
data type : specifies the type of value variable can hold

ex:

int
str
float
boolean 
None

"""

name = "hari"   # data type of name will be str

print(type(name))

age = 25 # data type of age will be int

print(type(age))

weight = 75.67 #data type of weight will be  float

print(type(weight))

is_active = True # data type of is_active boolean

print(type(is_active))

address = """ line 1 line 2 line3"""  # data type of address will be str

print(type(address))

open_to_work = "True"  # data type of open_to_work will be string

print(type(open_to_work))
